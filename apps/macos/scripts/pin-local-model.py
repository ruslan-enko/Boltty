#!/usr/bin/env python3
"""Writes Sources/Boltty/Services/LocalVoice/LocalVoiceCatalog.swift: every
file of each local voice model at one pinned Hugging Face commit, with its
size and SHA-256, so Boltty downloads exactly these bytes and nothing a
changed repository might serve later.

    python3 -I scripts/pin-local-model.py

To move a model to a newer commit, change its revision below and run it
again; the diff of the Swift file is the review. Large files carry their
SHA-256 in the tree (Git LFS); small ones are downloaded and hashed here.
"""
import hashlib
import json
import subprocess
import sys
from pathlib import Path

MODELS = [
    {
        "case": "parakeetUltra",
        "raw": "parakeet-ultra",
        "name": "Parakeet",
        "repository": "FluidInference/parakeet-ultra-coreml",
        "revision": "95eaa59a39d4394f047a4dc5cce480388a60d1b6",
        "licence": ("CC BY 4.0", "https://creativecommons.org/licenses/by/4.0/"),
        "include": [
            "Preprocessor.mlmodelc/",
            "Encoder.mlmodelc/",
            "Decoder.mlmodelc/",
            "JointDecisionv3.mlmodelc/",
            "parakeet_vocab.json",
        ],
    },
    {
        "case": "supertonic3",
        "raw": "supertonic-3",
        "name": "Supertonic",
        "repository": "FluidInference/supertonic-3-coreml",
        "revision": "2b5b939dfa1bca362c5212dcafeb8aadde90b1bc",
        "licence": ("BigScience OpenRAIL-M", "https://huggingface.co/Supertone/supertonic-3/blob/main/LICENSE"),
        "include": [
            "TextEncoder_v2.mlmodelc/",
            "DurationPredictor_v2.mlmodelc/",
            "Vocoder.mlmodelc/",
            "VectorEstimatorVariants/VectorEstimator_v2_L128_int8.mlmodelc/",
            "VectorEstimatorVariants/VectorEstimator_v2_L256_int8.mlmodelc/",
            "VectorEstimatorVariants/VectorEstimator_v2_L512_int8.mlmodelc/",
            "tts.json",
            "unicode_indexer.json",
            "voice_styles/",
            "LICENSE",
        ],
    },
]

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "Sources/Boltty/Services/LocalVoice/LocalVoiceCatalog.swift"


def fetch(url):
    # curl rather than urllib: the system Python's certificate store is not
    # the Keychain's.
    return subprocess.run(["curl", "-sfL", url], check=True, capture_output=True).stdout


def files(model):
    tree = json.loads(fetch(
        f"https://huggingface.co/api/models/{model['repository']}/tree/{model['revision']}?recursive=true"))
    chosen = []
    for item in tree:
        path = item["path"]
        if item["type"] != "file" or not any(
            path == rule or (rule.endswith("/") and path.startswith(rule)) for rule in model["include"]
        ):
            continue
        lfs = item.get("lfs")
        if lfs:
            size, digest = lfs["size"], lfs["oid"]
        else:
            body = fetch(f"https://huggingface.co/{model['repository']}/resolve/{model['revision']}/{path}")
            size, digest = len(body), hashlib.sha256(body).hexdigest()
        chosen.append((path, size, digest))
    missing = [rule for rule in model["include"] if not any(
        p == rule or (rule.endswith("/") and p.startswith(rule)) for p, _, _ in chosen)]
    if missing:
        sys.exit(f"{model['repository']}@{model['revision']}: nothing matches {missing}")
    return sorted(chosen)


def swift(models):
    lines = [
        "// Generated by scripts/pin-local-model.py. Do not edit by hand: change",
        "// the revision there and run it again.",
        "",
        "import Foundation",
        "",
        "enum LocalVoiceCatalog {",
        "  static let all: [LocalVoiceModel] = [" + ", ".join(m["case"] for m in models) + "]",
    ]
    for model in models:
        name, url = model["licence"]
        lines += [
            "",
            f"  static let {model['case']} = LocalVoiceModel(",
            f"    id: .{model['case']},",
            f"    name: \"{model['name']}\",",
            f"    repository: \"{model['repository']}\",",
            f"    revision: \"{model['revision']}\",",
            f"    licence: .init(name: \"{name}\", url: URL(string: \"{url}\")!),",
            "    files: [",
        ]
        for path, size, digest in model["files"]:
            lines.append(f"      .init(path: \"{path}\", size: {size}, sha256: \"{digest}\"),")
        lines += ["    ]", "  )"]
    lines.append("}")
    return "\n".join(lines) + "\n"


def main():
    for model in MODELS:
        model["files"] = files(model)
        total = sum(size for _, size, _ in model["files"])
        print(f"{model['raw']}: {len(model['files'])} files, {total / 1e6:.1f} MB")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(swift(MODELS), encoding="utf-8")
    print(OUT.relative_to(ROOT))


if __name__ == "__main__":
    main()
